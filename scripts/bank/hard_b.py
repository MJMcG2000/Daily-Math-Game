def maclaurin_coeff(f, power):
    return sp.series(f, x, 0, power + 1).removeO().coeff(x, power)


def arclen(f, lo, hi):
    """Arc length of y = f(x), integrated numerically from the raw formula."""
    return sp.Integral(sqrt(1 + diff(f, x)**2), (x, lo, hi)).evalf(30)


def ratio_radius(term):
    """Radius of convergence of sum term(n) * x^n (coefficient form) via the ratio test."""
    L = limit(sp.Abs(term.subs(n, n + 1) / term), n, oo)
    return oo if L == 0 else 1 / L


