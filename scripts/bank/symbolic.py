# Symbols named exactly like the problem variables (names are what matter for evaluation).
xs, as_, bs, ns, ks, rs, hs, ss, cs, ps, ys = sp.symbols('x a b n k r h s c p y', positive=True)
th = sp.Symbol('theta', real=True)


def sphere_rate():
    """dV/dt for V = 4/3 pi R(t)^3, with R' = k and R = r."""
    Rf = sp.Function('Rf')
    dv = diff(R(4, 3) * pi * Rf(t)**3, t)
    return dv.subs(diff(Rf(t), t), ks).subs(Rf(t), rs)


def V(*names, **domain):
    return {'variables': list(names), **({'domain': {k: list(v) for k, v in domain.items()}} if domain else {})}


