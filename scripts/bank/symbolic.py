"""Symbolic problems: the answer is an expression in one or more variables.

Each sets extra={'variables': [...], 'domain': {...}}. The game grades a guess by evaluating it and
the answer at several test points inside `domain`; verify.py compares the independent sympy
`check` with the stored answer at the same points.
"""
